"""
Real DICOM I/O -- the bridge between :mod:`prostate_deid.core`'s
in-memory ``Sample`` and actual ``.dcm`` files on disk, via ``pydicom``.

``load_sample`` and ``save_sample`` are the only two functions in the
library that touch a real ``pydicom.Dataset``. Every transform module
operates purely on the ``Sample`` dataclass (a NumPy array + a plain dict +
a list of audit entries), which keeps the transform logic independently
testable against synthetic in-memory fixtures without needing real DICOM
files for every unit test.
"""

from __future__ import annotations

import os
from typing import Any

import numpy as np

from .core import Sample

__all__ = ["load_sample", "save_sample"]

# Keywords pydicom already exposes with a stable name; anything else is
# surfaced under its "(GGGG,EEEE)" tag string, which is how private tags
# (with no keyword in the public dictionary) get exposed uniformly.
_SKIP_VR = {"SQ", "OB", "OW", "UN"}  # sequences / raw binary handled separately


def load_sample(path: str | os.PathLike) -> Sample:
    """Load a DICOM file into a :class:`~prostate_deid.core.Sample`.

    - Header identifiers are exposed as ``{keyword: value}`` in
      ``sample.dicom_meta``; private elements (no public keyword) are
      exposed under their ``"(GGGG,EEEE)"`` tag string instead.
    - Pixel data is decoded to a ``CZYX`` float32 array. 2D single-frame
      images become a ``(1, 1, H, W)`` array; multi-frame images become
      ``(1, N, H, W)``.
    - The full ``pydicom.Dataset`` is kept on ``sample.source_dataset`` so
      :func:`save_sample` can reconcile transform changes back into it
      rather than reconstructing a DICOM object from scratch.
    """
    import pydicom  # local import: keep pydicom optional at package import time

    ds = pydicom.dcmread(str(path))

    meta: dict[str, Any] = {}
    for elem in ds:
        if elem.tag == 0x7FE00010:  # PixelData handled separately
            continue
        key = elem.keyword if elem.keyword else f"({elem.tag.group:04X},{elem.tag.element:04X})"
        try:
            meta[key] = elem.value if elem.VR not in _SKIP_VR else str(elem.value)
        except Exception:
            meta[key] = None

    if hasattr(ds, "pixel_array"):
        pixels = ds.pixel_array.astype(np.float32)
    else:
        pixels = np.zeros((1, 1), dtype=np.float32)

    if pixels.ndim == 2:
        image = pixels[np.newaxis, np.newaxis, :, :]
    elif pixels.ndim == 3:
        image = pixels[np.newaxis, :, :, :]
    else:
        image = pixels

    return Sample(image=image, dicom_meta=meta, source_dataset=ds)


def save_sample(sample: Sample, path: str | os.PathLike) -> None:
    """Write a (possibly transformed) :class:`Sample` back out as a DICOM file.

    Reconciles every change the pipeline made:
      - deletes any keyword/private tag present on ``source_dataset`` but no
        longer present in ``sample.dicom_meta`` (i.e. removed by
        :class:`~prostate_deid.dicom_scrub.DicomTagScrub`);
      - writes back pseudonymized values for keywords still present but
        changed;
      - re-encodes pixel data only if ``sample.image_dirty`` is set, to
        avoid an unnecessary lossy round-trip when no pixel-touching
        transform ran;
      - sets ``PatientIdentityRemoved=YES`` and a ``DeidentificationMethod``
        free-text note, and keeps the file-meta SOP Instance UID in sync
        with any UID regenerated by :class:`~prostate_deid.pseudonymize.Pseudonymize`.
    """
    if sample.source_dataset is None:
        raise ValueError(
            "save_sample requires sample.source_dataset (set by load_sample); "
            "there is no real DICOM object to write back into for a "
            "synthetically constructed Sample."
        )

    ds = sample.source_dataset
    meta = sample.dicom_meta or {}

    original_keywords = {
        (elem.keyword if elem.keyword else f"({elem.tag.group:04X},{elem.tag.element:04X})")
        for elem in ds
        if elem.tag != 0x7FE00010
    }
    for key in original_keywords - set(meta.keys()):
        if key.startswith("(") and hasattr(ds, "get"):
            try:
                group, elem_num = (int(x, 16) for x in key.strip("()").split(","))
                if [group, elem_num] in ds:
                    del ds[group, elem_num]
            except Exception:
                pass
        elif hasattr(ds, key):
            delattr(ds, key)

    for key, value in meta.items():
        if not key.startswith("(") and hasattr(ds, key):
            try:
                setattr(ds, key, value)
            except Exception:
                pass

    if sample.image_dirty:
        pixels = np.squeeze(sample.image)
        out_dtype = ds.pixel_array.dtype if hasattr(ds, "pixel_array") else np.uint16
        ds.PixelData = pixels.astype(out_dtype).tobytes()
        ds.Rows, ds.Columns = pixels.shape[-2], pixels.shape[-1]

    ds.PatientIdentityRemoved = "YES"
    ds.DeidentificationMethod = "prostate-deid pipeline (see accompanying audit trail)"

    if "SOPInstanceUID" in meta:
        ds.SOPInstanceUID = meta["SOPInstanceUID"]
        if hasattr(ds, "file_meta") and ds.file_meta is not None:
            ds.file_meta.MediaStorageSOPInstanceUID = meta["SOPInstanceUID"]

    ds.save_as(str(path))
